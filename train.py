"""Train the v1 signal-quality model (standardised logistic regression over SQI features).

  python train.py --data data/windows.npz \
                  --header ../PCGKolect_rk/include/sqi_model_params.h

Reports patient-grouped 5-fold CV on PhysioNet windows, picks the GOOD / BAD
thresholds from the out-of-fold scores, fits the final model on everything and writes
  models/sqi_lr_v1.json            (Python reference)
  <header>                         (C++ constants for the RV1103, generated — do not edit)
"""
import argparse, json, os
import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score, balanced_accuracy_score, confusion_matrix
from sklearn.model_selection import GroupKFold
from sklearn.preprocessing import StandardScaler

from sqi_features import features, MODEL_FEATURES
from sqi_frontend import HP_SOS, DECIM_TAPS, CLIP_LEVEL, MODEL_PATH

C_REG = 0.1
MAX_BAD_AMONG_GOOD = 0.02   # GOOD threshold: <= 2 % of windows called GOOD are labelled bad
MIN_BAD_AMONG_BAD = 0.50    # BAD threshold: >= 50 % of windows called BAD are labelled bad
GATES = dict(clip_frac_max=0.001,   # > 0.1 % clipped samples in the scored 2 s
             level_dbfs_min=-60.0,  # PROVISIONAL: calibrate on the device (sensor off-chest)
             level_dbfs_max=-3.0)
HR_MIN_PERIODICITY = 0.3


def fit(F, y):
    sc = StandardScaler().fit(F)
    w = np.where(y == 0, (y == 1).sum() / max((y == 0).sum(), 1), 1.0)
    lr = LogisticRegression(C=C_REG, max_iter=5000).fit(sc.transform(F), y, sample_weight=w)
    return sc, lr


def predict(sc, lr, F):
    return lr.predict_proba(sc.transform(F))[:, 1]


def pick_thresholds(q, y):
    ts = np.linspace(0.01, 0.99, 197)
    t_good = next(t for t in ts if (y[q >= t] == 0).mean() <= MAX_BAD_AMONG_GOOD)
    t_bad = max([t for t in ts if t < t_good and (q < t).any() and (y[q < t] == 0).mean() >= MIN_BAD_AMONG_BAD],
                default=0.05)
    return float(t_good), float(t_bad)


def c_array(name, v, ctype='double'):
    return f'static const {ctype} {name}[{len(v)}] = {{\n    ' + ',\n    '.join(f'{x:.17g}' for x in v) + '\n};\n'


def write_header(path, m):
    h = ['// GENERATED by PCGKolect_model/train.py — do not edit by hand.',
         f'// Model: {m["name"]}  (CV AUC {m["cv"]["auc"]:.3f}, balanced acc {m["cv"]["balanced_acc"]:.3f})',
         '#pragma once', '', 'namespace sqi_params {', '',
         f'static const int kNumFeatures = {len(MODEL_FEATURES)};',
         '// ' + ', '.join(MODEL_FEATURES),
         c_array('kMean', m['mean']), c_array('kScale', m['scale']), c_array('kCoef', m['coef']),
         f'static const double kIntercept = {m["intercept"]:.17g};', '',
         f'static const double kThreshGood = {m["t_good"]:.17g};',
         f'static const double kThreshBad = {m["t_bad"]:.17g};',
         f'static const double kClipFracMax = {m["gates"]["clip_frac_max"]:.17g};',
         f'static const double kLevelDbfsMin = {m["gates"]["level_dbfs_min"]:.17g};',
         f'static const double kLevelDbfsMax = {m["gates"]["level_dbfs_max"]:.17g};',
         f'static const double kHrMinPeriodicity = {m["hr_min_periodicity"]:.17g};',
         f'static const int kClipLevel = {CLIP_LEVEL};', '',
         '// 2 kHz high-pass biquad: b0 b1 b2 a0 a1 a2',
         c_array('kHpSos', list(HP_SOS)),
         '// 8 kHz -> 2 kHz anti-alias FIR',
         c_array('kDecimTaps', list(DECIM_TAPS)),
         '} // namespace sqi_params', '']
    with open(path, 'w') as f:
        f.write('\n'.join(h))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--data', default='data/windows.npz')
    ap.add_argument('--header', default='../PCGKolect_rk/include/sqi_model_params.h')
    a = ap.parse_args()
    d = np.load(a.data)
    keep = np.char.startswith(d['src'], 'pn')       # train/evaluate on the hand-labelled corpus
    X, y, grp, src = d['X'][keep], d['y'][keep], d['group'][keep], d['src'][keep]
    F = np.concatenate([features(X[i:i + 4096]) for i in range(0, len(X), 4096)])[:, :len(MODEL_FEATURES)]
    print(f'{len(y)} windows, {(y == 0).sum()} bad, {len(set(grp))} recordings')

    oof = np.zeros(len(y))
    for tr, te in GroupKFold(5).split(F, y, grp):
        sc, lr = fit(F[tr], y[tr])
        oof[te] = predict(sc, lr, F[te])
    auc = roc_auc_score(y, oof)
    t_good, t_bad = pick_thresholds(oof, y)
    verdict = np.where(oof >= t_good, 'GOOD', np.where(oof >= t_bad, 'MARGINAL', 'BAD'))
    cv = dict(auc=float(auc), balanced_acc=float(balanced_accuracy_score(y, oof >= 0.5)),
              per_subset={s: float(roc_auc_score(y[src == s], oof[src == s]))
                          for s in sorted(set(src)) if len(set(y[src == s])) == 2},
              verdict_vs_label={v: {'good': int(((verdict == v) & (y == 1)).sum()),
                                    'bad': int(((verdict == v) & (y == 0)).sum())}
                                for v in ('GOOD', 'MARGINAL', 'BAD')})
    print(json.dumps(cv, indent=1))
    print(f't_good={t_good:.3f}  t_bad={t_bad:.3f}')
    print('confusion @0.5 [[bad->bad, bad->good],[good->bad, good->good]]\n', confusion_matrix(y, oof >= 0.5))

    sc, lr = fit(F, y)
    m = dict(name='sqi_lr_v1', features=MODEL_FEATURES, mean=sc.mean_.tolist(), scale=sc.scale_.tolist(),
             coef=lr.coef_[0].tolist(), intercept=float(lr.intercept_[0]), t_good=t_good, t_bad=t_bad,
             gates=GATES, hr_min_periodicity=HR_MIN_PERIODICITY, cv=cv,
             trained_on='PhysioNet/CinC 2016 hand-corrected noise annotations (subsets present locally)')
    os.makedirs(os.path.dirname(MODEL_PATH), exist_ok=True)
    with open(MODEL_PATH, 'w') as f:
        json.dump(m, f, indent=1)
    write_header(a.header, m)
    print('wrote', MODEL_PATH, 'and', a.header)
    print('weights:', sorted(zip(np.round(lr.coef_[0], 2), MODEL_FEATURES), key=lambda t: -abs(t[0])))


if __name__ == '__main__':
    main()
