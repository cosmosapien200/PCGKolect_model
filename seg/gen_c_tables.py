"""Emit PCGKolect_rk/include/seg_params.h from seg/model.py + seg/decode.py (single source of truth).

  python seg/gen_c_tables.py [--out ../PCGKolect_rk/include/seg_params.h]
"""
import argparse, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import model as M  # noqa: E402
import decode as D  # noqa: E402


def arr(name, v, ctype='double'):
    return f'static const {ctype} {name}[{len(v)}] = {{' + ', '.join(f'{x:.17g}' for x in v) + '};'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(HERE, '..', '..', 'PCGKolect_rk', 'include', 'seg_params.h'))
    a = ap.parse_args()
    fb_rows = [arr(f'kFbRow{i}', M.FB[i]) for i in range(M.NBANDS)]
    L = ['// GENERATED by PCGKolect_model/seg/gen_c_tables.py — do not edit by hand.',
         '#pragma once', '', 'namespace seg_params {', '',
         f'static const int kFs = {M.FS};', f'static const int kNfft = {M.NFFT};', f'static const int kHop = {M.HOP};',
         f'static const int kBands = {M.NBANDS};', f'static const int kFrames = {M.FRAMES};',
         f'static const int kSamples = {M.SAMPLES};', f'static const double kFeatScale = {M.FEAT_SCALE:.17g};',
         f'static const int kNoise = {M.NOISE};', '',
         '// periodic Hann window', arr('kHann', M.HANN), '',
         f'// triangular filterbank [{M.NBANDS}][{M.NFFT // 2 + 1}]'] + fb_rows + [
         'static const double* const kFb[%d] = {%s};' % (M.NBANDS, ', '.join(f'kFbRow{i}' for i in range(M.NBANDS))), '',
         '// beat decoder (seg/decode.py)',
         f'static const int kFps = {D.FPS};',
         arr('kMinDur', D.MIN_DUR, 'int'), arr('kMeanDur', D.MEAN_DUR, 'double'),
         f'static const double kPToNoise = {D.P_TO_NOISE:.17g};', f'static const double kEps = {D.EPS:.17g};',
         f'static const double kBeatMinS = {D.BEAT_MIN_S:.17g};', f'static const double kBeatMaxS = {D.BEAT_MAX_S:.17g};',
         f'static const double kBeatConfMin = {D.BEAT_CONF_MIN:.17g};', f'static const double kRhythmTol = {D.RHYTHM_TOL:.17g};',
         '', '} // namespace seg_params', '']
    with open(a.out, 'w') as f:
        f.write('\n'.join(L))
    print('wrote', a.out)


if __name__ == '__main__':
    main()
